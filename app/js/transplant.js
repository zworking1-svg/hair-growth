// Что ожидать в конкретной зоне на текущем сроке.
export function zoneExpectation(zoneId, months) {
  const lag = ZONE_LAG[zoneId] ?? 0;
  const eff = Math.max(0, months - lag);
  const st = stageFor(eff);
  const pct = st.pct ? `${st.pct[0]}–${st.pct[1]}%` : null;
  return { effMonths: eff, stage: st, pct, lag };
}
